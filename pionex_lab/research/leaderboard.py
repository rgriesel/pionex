"""Regenerate research/LEADERBOARD.md: every logged test, ranked by return per unit of ruin probability.

Run:  py -m pionex_lab.research.leaderboard

Inputs: docs/STRATEGY_LOG.md (every row of every results table, PASS or FAIL) and
var/reports/ruin_*.json written by `research/ruin.save` (one per test, with a `log_match` substring that
identifies its log row). Rows with a ruin report are ranked by return_per_ruin (median 30-day return
per unit of P(equity <= $50 within 30 days), $100 start, out-of-sample trades; see ruin.py). Rows whose
ruin run is INSUFFICIENT, or that have no OOS trade list yet, are listed below the ranking: nothing is
hidden. Not proof of profit.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

VERDICT = re.compile(r"\b(PASS|FAIL|INSUFFICIENT|REJECTED)\b")


def parse_log(text: str) -> list[dict]:
    rows = []
    for line in text.splitlines():
        if not re.match(r"\|\s*20\d\d-", line):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 4:
            continue
        m = VERDICT.findall(cells[-1])
        rows.append({"date": cells[0], "idea": cells[1], "verdict": m[0] if m else "see log", "text": line})
    return rows


def _short(s: str, n: int = 90) -> str:
    s = re.sub(r"[*`]", "", s).replace("|", "/")
    return s if len(s) <= n else s[: n - 1] + "…"


def _pct(x) -> str:
    return "—" if x is None else f"{100 * x:+.1f}%"


def build(log_text: str, ruin_reports: list[dict]) -> str:
    rows = parse_log(log_text)
    used = set()
    ranked, thin, none = [], [], []
    for r in rows:
        hit = next((i for i, x in enumerate(ruin_reports) if x.get("log_match") and x["log_match"] in r["text"]), None)
        if hit is None:
            none.append(r)
            continue
        used.add(hit)
        ru = ruin_reports[hit]["ruin"]
        (ranked if ru.get("verdict") == "OK" else thin).append((r, ru))
    for i, x in enumerate(ruin_reports):          # ruin reports whose test is not (yet) in the log
        if i not in used:
            r = {"date": "—", "idea": x.get("title", "?") + " (not in STRATEGY_LOG yet)", "verdict": "unlogged"}
            (ranked if x["ruin"].get("verdict") == "OK" else thin).append((r, x["ruin"]))
    ranked.sort(key=lambda p: p[1]["return_per_ruin"], reverse=True)
    out = ["# Leaderboard — return per unit of risk-of-ruin", "",
           "Generated by `py -m pionex_lab.research.leaderboard` from `docs/STRATEGY_LOG.md` and "
           "`var/reports/ruin_*.json`. Do not edit by hand.", "",
           "Method (`pionex_lab/research/ruin.py`): out-of-sample trades only, $100 start, 5-day block "
           "bootstrap, 10,000 resamples of 30 days; ruin = equity <= $50 at any daily close. "
           "Return per ruin = median 30-day return / max(P(ruin), 1/10,000). A descriptive resampling of "
           "past data on PROXY prices, not a forecast and not proof of profit; a high rank on a failed test "
           "means little, so read the verdict column.", "",
           "## Ranked", "",
           "| # | Test | Log verdict | P(ruin) | Median 30d | p5 / p95 30d | Return per ruin | OOS days / trades |",
           "|---|---|---|---|---|---|---|---|"]
    for k, (r, ru) in enumerate(ranked, 1):
        floor = " (floor)" if ru.get("ruin_floor_applied") else ""
        out.append(f"| {k} | {_short(r['idea'])} | {r['verdict']} | {100 * ru['p_ruin']:.2f}% | "
                   f"{_pct(ru['median_30d_return'])} | {_pct(ru['p5_30d_return'])} / {_pct(ru['p95_30d_return'])} | "
                   f"{ru['return_per_ruin']:+.2f}{floor} | {ru['n_days']} / {ru.get('n_trades', '—')} |")
    if not ranked:
        out.append("| — | no test has a ruin report yet | | | | | | |")
    out += ["", "## Ruin run INSUFFICIENT (too few out-of-sample days)", "", "| Test | Log verdict | Reason |", "|---|---|---|"]
    out += [f"| {_short(r['idea'])} | {r['verdict']} | {ru.get('reason', '')} |" for r, ru in thin] or ["| — | | |"]
    out += ["", "## Logged, no out-of-sample ruin report yet", "", "| Date | Test | Log verdict |", "|---|---|---|"]
    out += [f"| {r['date']} | {_short(r['idea'])} | {r['verdict']} |" for r in none]
    return "\n".join(out) + "\n"


def main(root: Path | None = None) -> Path:
    from ..paths import Paths
    root = root or Path(__file__).resolve().parents[2]
    log = (root / "docs" / "STRATEGY_LOG.md").read_text(encoding="utf-8")
    rep_dir = Paths.default().reports
    reports = [json.loads(p.read_text(encoding="utf-8")) for p in sorted(rep_dir.glob("ruin_*.json"))]
    dst = root / "research" / "LEADERBOARD.md"
    dst.write_text(build(log, reports), encoding="utf-8")
    return dst


if __name__ == "__main__":
    print(main())
